/** Look up a breed by its stable catalogue id (case-insensitive). */
export function getBreedById(
  id: string | null | undefined,
): Breed | undefined {
  const normalised = id?.trim().toLowerCase();
  if (!normalised) return undefined;
  return ALL_BREEDS.find((breed) => breed.id === normalised);
}
